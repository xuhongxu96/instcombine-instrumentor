import { describe, expect, it } from "vitest";
import { deriveOpcode } from "./opcode";

describe("deriveOpcode", () => {
  it.each([
    ["add", "%a = add i32 %x, 0"],
    ["add", "  \t%12 = add nuw nsw i32 %x, 1"],
    ["add", "%1=add i32 %x, 1"],
    ["add", "%.tmp$1-foo = add i32 %x, 1"],
    ["add", '%"name = call" = add i32 %x, 1'],
    ["add", String.raw`%"name \22 = call\22" = add i32 %x, 1`],
    ["add", "<badref> = add i32 <badref>, 1"],
    ["fadd", "%r = fadd fast float %x, %y"],
    ["fneg", "%r = fneg double %x"],
    ["frem", "%r = frem double %x, %y"],
    ["freeze", "%r = freeze i32 %x"],
    ["call", "%r = call fastcc i32 @f()"],
    ["call", "%r = tail call i32 @f()"],
    ["call", "%r = musttail call i32 @f()"],
    ["call", "%r = notail call i32 @f()"],
    ["call", "tail call void @f()"],
    ["call", "call void @llvm.assume(i1 true)"],
    ["call", 'call void asm sideeffect "add $0, $1", ""()'],
    ["store", "store volatile i32 0, ptr %p"],
    ["load", "%r = load atomic volatile i32, ptr %p seq_cst, align 4"],
    ["load", "%r = load i32* %p"],
    ["atomicrmw", "%r = atomicrmw add ptr %p, i32 1 monotonic"],
    ["cmpxchg", "%r = cmpxchg weak volatile ptr %p, i32 0, i32 1 seq_cst monotonic"],
    ["fence", "fence seq_cst"],
    ["getelementptr", "%r = getelementptr inbounds i32, ptr %p, i64 1"],
    ["addrspacecast", "%r = addrspacecast i8* %p to i8 addrspace(1)*"],
    ["ptrtoaddr", "%r = ptrtoaddr ptr %p to i64"],
    ["va_arg", "%r = va_arg ptr %args, i32"],
    ["icmp", "%r = icmp eq i32 %x, 0"],
    ["phi", "%r = phi i32 [ 0, %entry ], [ 1, %next ]"],
    ["extractvalue", "%r = extractvalue { i32, i8 } %pair, 0"],
    ["shufflevector", "%r = shufflevector <2 x i32> %a, <2 x i32> %b, <2 x i32> zeroinitializer"],
    ["ret", "ret void"],
    ["br", "br label %next"],
    ["switch", "switch i32 %x, label %default [\n  i32 0, label %zero\n]"],
    ["invoke", "%r = invoke i32 @f()\n  to label %ok unwind label %error"],
    ["callbr", "callbr void asm sideeffect \"\", \"!i\"()\n  to label %ok [label %other]"],
    ["landingpad", "%r = landingpad { ptr, i32 }\n  cleanup"],
    ["catchswitch", "%r = catchswitch within none [label %handler] unwind to caller"],
    ["unreachable", "unreachable"],
    ["unreachable", "  unreachable, !dbg !12\n"],
    ["add", "%a = add i32 %x, 0, !dbg !12"],
  ])("extracts %s from %j", (opcode, ir) => {
    expect(deriveOpcode(ir)).toBe(opcode);
  });

  it.each([
    "",
    " \t\n",
    "i32 %x",
    "%add %x",
    "i32 0",
    "ptr null",
    "i32 undef",
    "i32 poison",
    "<2 x i32> zeroinitializer",
    "ptr getelementptr (i8, ptr @g, i64 1)",
    "i8* bitcast (i32* @g to i8*)",
    'ptr asm "add $0, $1", ""',
    "Sentinel(1)",
    "unknown_opcode i32 %x",
    "%r = future_opcode i32 %x",
    "%r = add_extra i32 %x, 1",
    "%r = add",
    "ret",
    "%r = tail call",
    "%r =",
    "%r = add, !dbg !12",
    "%r = add\nret void",
    "tail add i32 %x, 1",
    '%"unfinished = add i32 %x, 1',
    '@g = global [3 x i8] c"add"',
    "define i32 @f(i32 %x) {\n  %r = add i32 %x, 0\n  ret i32 %r\n}",
    "declare i32 @add(i32)",
    "entry:\n  %r = add i32 %x, 0\n  ret i32 %r",
    "add:\n  ret void",
    "; comment mentioning add\n  %r = add i32 %x, 0",
    '!0 = !{!"add"}',
  ])("returns empty for non-instruction or unrecognized text %j", (ir) => {
    expect(deriveOpcode(ir)).toBe("");
  });
});
